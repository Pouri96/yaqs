"""Restores a conserved expectation value after an SVD compression sweep.

Enabled per run through :class:`~mqt.yaqs.AnalogSimParams`, not by calling this module
directly::

    AnalogSimParams(
        ...,
        conserve_energy=True,  # restore <H>
        conserve_observables={"M": magnetization_mpo},  # and any commuting Hermitian MPO
    )

An uncompressed sweep of either supported integrator preserves ``<psi|H|psi>``, since its
local updates are generated by Hermitian effective Hamiltonians. The truncation discards
weight from the state and with it a portion of that quantity, so the compressed composition
conserves neither the norm nor the energy. This module appends a correction to the
compression that restores the energy exactly and changes no bond dimension.

- BUG compresses twice per step, once per half-sweep, and the center is the endpoint each
  compression leaves. The correction runs inside the step, after the truncation and before
  the center is renormalized; the Rayleigh quotient is scale invariant, so the subsequent
  rescale leaves the restored value unchanged.
- TDVP truncates at every local two-site split, but its substep is symmetric and every
  sweep integrator ends at ``state.set_center(0)``. The completed step therefore leaves one
  center, at site ``0``, and the correction runs there, once per step. Because the quotient
  is scale invariant the correction neither requires nor performs a renormalization, so
  TDVP's own norm handling is untouched.

The correction is structure preservation. It restores the invariant exactly; it does not
reduce the compression error. Beyond the energy, additional conserved quantities -- Hermitian
MPOs commuting with the Hamiltonian, such as the total magnetization of a spin chain -- can be
restored through the same mechanism. With two or more quantities configured, the corrections
are solved together (:func:`restore_invariants_joint`): a scalar correction for one quantity
perturbs every other at first order in its multiplier, so applied in sequence only the last
one survives. Note that under a noise model no expectation value is an invariant of the
trajectory, and :func:`validate_conservation` rejects that combination.

Only invariants of the low-rank dynamics can be restored: the energy, and any sum of on-site
operators, which covers the abelian charges. A conserved quantity that is not such a sum,
for instance the total spin of an SU(2)-symmetric chain, drifts before any weight is
discarded, and restoring it pins a value the dynamics does not maintain.
"""

from __future__ import annotations

import math
from typing import TYPE_CHECKING, NamedTuple

import numpy as np

from .tdvp.primitives import project_site, update_left_environment, update_right_environment

